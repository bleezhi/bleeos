static const u8 *glyph(char c) {
    if (c < 0x20 || c > 0x7E) return font[0];
    return font[c - 0x20];
}

/* glyph for external users (fbcon); same 0x20-0x7E coverage */
const u8 *gfx_glyph(char c) { return glyph(c); }

void gfx_textn(int x, int y, const char *s, int n, u32 fg, u32 bg) {
    for (int i = 0; i < n && s[i]; i++) {
        const u8 *g = glyph(s[i]);
        for (int row = 0; row < 8; row++) {
            u8 bits = g[row];
            for (int col = 0; col < 8; col++) {
                if (bits & (0x80 >> col))
                    gfx_pixel(x + i * 8 + col, y + row, fg);
                else if (bg != GFX_TRANS)
                    gfx_pixel(x + i * 8 + col, y + row, bg);
            }
        }
    }
}
void gfx_text(int x, int y, const char *s, u32 fg, u32 bg) {
    int n = 0;
    while (s[n]) n++;
    gfx_textn(x, y, s, n, fg, bg);
}
int gfx_textw(const char *s) {
    int n = 0;
    while (s[n]) n++;
    return n * 8;
}

void gfx_present(void) {
    if (fpitch == fw) {
        u32 n = (u32)(fw * fh);
        u32 *s = draw, *d = fb;
        __asm__ volatile ("cld; rep movsl"
                          : "+S" (s), "+D" (d), "+c" (n)
                          : : "memory");
        return;
    }
    for (int y = 0; y < fh; y++) {
        u32 *s = draw + (u32)(y * fw), *d = fb + (u32)(y * fpitch);
        u32 n = (u32)fw;
        __asm__ volatile ("cld; rep movsl"
                          : "+S" (s), "+D" (d), "+c" (n)
                          : : "memory");
    }
}
