/* Framebuffer drawing + built-in 8x8 font (chars 0x20-0x7E). */
#include "gfx.h"

/* Double buffering: everything draws into a shadow buffer in extended
 * memory (1MB+, free: kernel ends below 640K, nothing lives above 1MB),
 * sized for the largest allowed mode (1920x1200x32, ends near 10MB).
 * Only the current frame's bytes are ever touched.
 * gfx_present() blits one full frame to the visible LFB. Drawing to
 * cacheable RAM + a single rep-movsl flush beats per-pixel LFB writes
 * and eliminates mid-frame tearing. */
#define SHADOW_BASE ((u32 *)0x100000u)

static u32 *fb;    /* visible LFB */
static u32 *draw;  /* shadow buffer */
static int fw, fh, fpitch;   /* fpitch = pixels per LFB scanline (>= fw) */
static int cx0, cy0, cx1, cy1;   /* clip rect, exclusive max */

void gfx_init_pitch(u32 *f, int w, int h, int pitch) {
    fb = f; fw = w; fh = h; fpitch = pitch >= w ? pitch : w;
    if (!draw) draw = SHADOW_BASE;
    gfx_noclip();
}
void gfx_init(u32 *f, int w, int h) {
    gfx_init_pitch(f, w, h, w);
}
void gfx_clip(int x, int y, int w, int h) {
    cx0 = x < 0 ? 0 : x; cy0 = y < 0 ? 0 : y;
    cx1 = x + w; cy1 = y + h;
    if (cx1 > fw) cx1 = fw;
    if (cy1 > fh) cy1 = fh;
}
void gfx_noclip(void) { cx0 = 0; cy0 = 0; cx1 = fw; cy1 = fh; }
int gfx_w(void) { return fw; }
int gfx_h(void) { return fh; }

void gfx_pixel(int x, int y, u32 c) {
    if (x < cx0 || y < cy0 || x >= cx1 || y >= cy1) return;
    draw[y * fw + x] = c;
}
void gfx_fill(int x, int y, int w, int h, u32 c) {
    if (x < cx0) { w -= cx0 - x; x = cx0; }
    if (y < cy0) { h -= cy0 - y; y = cy0; }
    if (x + w > cx1) w = cx1 - x;
    if (y + h > cy1) h = cy1 - y;
    if (w <= 0 || h <= 0) return;
    for (int j = 0; j < h; j++) {
        u32 *row = draw + (y + j) * fw + x;
        for (int i = 0; i < w; i++) row[i] = c;
    }
}
void gfx_hline(int x, int y, int w, u32 c) { gfx_fill(x, y, w, 1, c); }
void gfx_vline(int x, int y, int h, u32 c) { gfx_fill(x, y, 1, h, c); }
void gfx_rect(int x, int y, int w, int h, u32 c) {
    gfx_hline(x, y, w, c);
    gfx_hline(x, y + h - 1, w, c);
    gfx_vline(x, y, h, c);
    gfx_vline(x + w - 1, y, h, c);
}

